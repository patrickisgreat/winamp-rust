//! Every user-triggerable command, shared by buttons, menus and hotkeys.

use winamp_playlist::SortKey;

#[derive(Clone, Debug, PartialEq)]
pub enum Cmd {
    // transport
    Prev,
    Play,
    Pause,
    Stop,
    Next,
    SeekRelative(f64),
    SeekTo(f64),
    VolumeDelta(f32),
    SetVolume(f32),
    SetBalance(f32),
    ToggleShuffle,
    ToggleRepeat,
    PlayIndex(usize),
    // files
    OpenFiles,
    OpenDirectory,
    OpenUrl,
    AddFiles,
    AddDirectory,
    AddUrl,
    /// Play a URL immediately (appends it to the playlist).
    PlayUrl(String),
    QueueUrl(String),
    // windows
    ToggleMain,
    ToggleEq,
    TogglePlaylist,
    ToggleMainShade,
    ToggleEqShade,
    TogglePlShade,
    ToggleDoubleSize,
    ToggleAlwaysOnTop,
    ToggleLockWindows,
    MinimizeAll,
    Exit,
    // display
    ToggleTimeMode,
    CycleVisMode,
    SetVisMode(crate::config::VisMode),
    ToggleAnalyzerStyle,
    ToggleAnalyzerPeaks,
    ToggleScrollTitle,
    ToggleMilkdrop,
    /// +1 next, -1 previous, 0 random.
    MilkdropPreset(i32),
    MilkdropSetPreset(usize),
    MilkdropFullscreen,
    // equalizer
    ToggleEqEnabled,
    ToggleEqAuto,
    EqPresetsDialog,
    LoadPreset(String),
    LoadBuiltinPreset(usize),
    SavePreset(String),
    DeletePreset(String),
    SaveAutoPreset,
    DeleteAutoPreset,
    LoadPresetFile,
    SavePresetFile,
    EqFlat,
    SetPreamp(f32),
    SetBand(usize, f32),
    // playlist editing
    PlRemoveSelected,
    PlRemoveAll,
    PlCrop,
    PlRemoveMissing,
    PlRemoveDuplicates,
    PlSelectAll,
    PlSelectNone,
    PlInvertSelection,
    PlSort(SortKey),
    PlReverse,
    PlRandomize,
    PlMoveSelected(i32),
    PlNew,
    PlSave,
    PlLoad,
    PlPlaySelected,
    PlFileInfo,
    // dialogs
    JumpToFile,
    JumpToTime,
    FileInfo,
    Preferences,
    SkinBrowser,
    About,
    LoadSkin(Option<std::path::PathBuf>),
    Nop,
}
